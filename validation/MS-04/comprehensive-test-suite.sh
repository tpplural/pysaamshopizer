# Extract a top-level field from a JSON response (nested-object safe).
# Usage: extract_field "$LAST_BODY" "id"
extract_field() {
    local json=$1
    local field=$2
    if command -v jq &>/dev/null; then
        echo "$json" | jq -r ".$field"
    else
        echo "$json" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('$field',''))"
    fi
}

# Assert HTTP status only.
assert_status() {
    local test_num=$1
    local test_name=$2
    local rule_id=$3
    local http_method=$4
    local url=$5
    local payload=$6
    local expected_status=$7

    TOTAL=$((TOTAL + 1))
    echo -e "\n${BLUE}Test $test_num: $test_name${NC}"
    echo -e "  Rule: $rule_id | Expected Status: $expected_status"

    if [ -n "$payload" ] && [ "$payload" != "null" ]; then
        actual_status=$(curl -s -o /dev/null -w '%{http_code}' -X "$http_method" "$url" \
            -H 'Content-Type: application/json' -H "$TENANT_HEADER" -H "$CORRELATION_HEADER" -d "$payload")
    else
        actual_status=$(curl -s -o /dev/null -w '%{http_code}' -X "$http_method" "$url" \
            -H "$TENANT_HEADER" -H "$CORRELATION_HEADER")
    fi

    if [ "$actual_status" = "$expected_status" ]; then
        echo -e "  ${GREEN}✅ PASSED${NC} (HTTP $actual_status)"
        PASSED=$((PASSED + 1))
        return 0
    else
        echo -e "  ${RED}❌ FAILED${NC} (Expected: $expected_status, Got: $actual_status)"
        FAILED=$((FAILED + 1))
        FAILED_TESTS+=("Test $test_num: $test_name [$rule_id] - Expected $expected_status, Got $actual_status")
        return 1
    fi
}

# Assert a fixed-string pattern is present in the response body.
# Use this (NOT regex) for numbers/decimals/prices — avoids bash regex escaping pitfalls.
assert_json_field() {
    local test_num=$1
    local test_name=$2
    local rule_id=$3
    local http_method=$4
    local url=$5
    local payload=$6
    local json_pattern=$7

    TOTAL=$((TOTAL + 1))
    echo -e "\n${BLUE}Test $test_num: $test_name${NC}"
    echo -e "  Rule: $rule_id | Expected pattern: $json_pattern"

    if [ -n "$payload" ] && [ "$payload" != "null" ]; then
        result=$(curl -s -X "$http_method" "$url" \
            -H 'Content-Type: application/json' -H "$TENANT_HEADER" -H "$CORRELATION_HEADER" -d "$payload")
    else
        result=$(curl -s -X "$http_method" "$url" -H "$TENANT_HEADER" -H "$CORRELATION_HEADER")
    fi

    if echo "$result" | grep -qF "$json_pattern"; then
        echo -e "  ${GREEN}✅ PASSED${NC}"
        PASSED=$((PASSED + 1))
        return 0
    else
        echo -e "  ${RED}❌ FAILED${NC}"
        echo "  Expected pattern: $json_pattern"
        echo "  Got: $(echo "$result" | head -c 300)"
        FAILED=$((FAILED + 1))
        FAILED_TESTS+=("Test $test_num: $test_name [$rule_id] - Pattern '$json_pattern' not found")
        return 1
    fi
}

# Capture BOTH status code AND response body in a single request.
# Sets globals: LAST_STATUS and LAST_BODY.
capture_with_status() {
    local http_method=$1
    local url=$2
    local payload=$3
    local response

    if [ -n "$payload" ] && [ "$payload" != "null" ]; then
        response=$(curl -s -w "\n%{http_code}" -X "$http_method" "$url" \
            -H 'Content-Type: application/json' -H "$TENANT_HEADER" -H "$CORRELATION_HEADER" -d "$payload")
    else
        response=$(curl -s -w "\n%{http_code}" -X "$http_method" "$url" \
            -H "$TENANT_HEADER" -H "$CORRELATION_HEADER")
    fi

    LAST_STATUS=$(echo "$response" | tail -1)
    LAST_BODY=$(echo "$response" | sed '$d')
}

# Assert status + capture body in one request (prevents double-POST).
assert_status_and_capture() {
    local test_num=$1
    local test_name=$2
    local rule_id=$3
    local http_method=$4
    local url=$5
    local payload=$6
    local expected_status=$7

    TOTAL=$((TOTAL + 1))
    echo -e "\n${BLUE}Test $test_num: $test_name${NC}"
    echo -e "  Rule: $rule_id | Expected Status: $expected_status"

    capture_with_status "$http_method" "$url" "$payload"

    if [ "$LAST_STATUS" = "$expected_status" ]; then
        echo -e "  ${GREEN}✅ PASSED${NC} (HTTP $LAST_STATUS)"
        PASSED=$((PASSED + 1))
        return 0
    else
        echo -e "  ${RED}❌ FAILED${NC} (Expected: $expected_status, Got: $LAST_STATUS)"
        FAILED=$((FAILED + 1))
        FAILED_TESTS+=("Test $test_num: $test_name [$rule_id] - Expected $expected_status, Got $LAST_STATUS")
        return 1
    fi
}

